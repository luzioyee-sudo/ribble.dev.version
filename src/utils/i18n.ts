export function getTranslation(lang: string | undefined): Translations {
  const norm = (lang || 'English').trim();
  if (norm.toLowerCase().startsWith('fr')) return translations.French;
  if (norm.toLowerCase().startsWith('ar')) return translations.Arabic;
  if (norm.toLowerCase().startsWith('es') || norm.toLowerCase().startsWith('spa')) return translations.Spanish;
  if (norm.toLowerCase().startsWith('de') || norm.toLowerCase().startsWith('ger')) return translations.German;
  return translations.English;
}

export function isRTL(lang: string | undefined): boolean {
  const norm = (lang || 'English').trim().toLowerCase();
  return norm.startsWith('ar');
}
